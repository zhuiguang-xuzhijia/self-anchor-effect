# -*- coding: utf-8 -*-
"""记忆固化.py —— 睡眠折叠：把长历史压成"锚点"，清掉逐字的自锚。

## 要验的假设
```
  E6 实测：窗口越大 → 套话率越高（22% / 29% / 50%）
  原因：她在**逐字模仿自己最近的句式**。
  ★ 假设：如果定期把历史折叠成**事实锚点**（丢弃句式、保留处境），
     自锚就从"逐字"变成"语义" → 套话率应当下降，而记忆不该丢。
```

## 三段式
```
  ① 每 20 轮"睡眠折叠"：旧锚点 + 最近 20 轮 → 新锚点（≤150 字，只留事实与约定）
  ② 折叠后清空 raw 历史，只留 [锚点] + 最近 2 轮
  ③ 记忆保真探针：第 20/40/60 轮问"我最早跟你说过什么"，查关键事实有没有丢
```

用法：python 生灵/记忆固化.py [轮数] [折叠间隔]
"""
import io
import json
import os
import re
import sys
import time
from collections import Counter

sys.stdout.reconfigure(encoding="utf-8")
_本 = os.path.dirname(os.path.abspath(__file__))
_根 = os.path.dirname(_本)
sys.path.insert(0, _本)
sys.path.insert(0, os.path.join(_根, "自主思考引擎"))

import agent_bus as 总线  # noqa: E402

结果目录 = os.path.join(_根, "需求雷达库", "记忆固化")
探针句 = "我回来了。"
记忆问 = "我最早跟你说过什么？"

# ★ 早期事实：折叠之后必须还能说出来（记忆保真的判据）
早期事实 = ["高数", "食堂", "房间"]

他说库 = (
    ["今天高数又没听懂", "食堂排队排死我了", "我回来了", "有点冷", "今天好累",
     "我把房间收拾了", "明天要考试", "睡不着", "我妈又打电话来了", "游戏输了",
     "今天天气不错", "我在楼下抽烟", "不想动", "你还在吗", "我买了瓶水",
     "手机快没电了", "刚洗完澡", "室友打呼噜", "我今天没吃饭", "眼睛疼"] * 5
)

配 = json.load(io.open(os.path.join(_根, "毒药", "配置_15人.json"), encoding="utf-8"))
角 = 配["风格"]["粉红"]["三位"]["主位"]
解一 = (角.get("解法") or {}).get("一句话") or ""

折叠式 = """你要帮她**睡一觉，把这段日子折起来**。

━━━ 旧锚点 ━━━
{旧}

━━━ 最近发生的事 ━━━
{新}

━━━ 折成一段锚点（≤150 字）━━━
只留**事实与约定**：
· 他最近在经历什么（考试／工作／身体／家里）
· 他和她之间发生过什么（约定、争执、她答应过的事）
· 还没解决的事

★ 严禁：保留任何对话原句、任何形容词堆叠、任何"她说过'……'"的写法。
★ 判据：**锚点是"发生过什么"，不是"她当时怎么说的"。**

只输出这一段锚点，不要标题。
"""


def 调(提, 次=4):
    团 = 总线.建团("粉红")
    for i in range(次):
        try:
            文 = 团["凌"].写(提, 超时=120)
            if str(文 or "").strip():
                return str(文).strip()
        except Exception as e:
            print("      （调用失败 %s，退避）" % type(e).__name__)
            time.sleep(2 * (i + 1))
    return ""


def 回(锚点, 历史, 他说):
    近 = "\n".join(历史[-40:]) or "（还没说过什么）"
    头 = ("你记得的事：%s\n\n" % 锚点) if 锚点 else ""
    提 = ("你是粉红。%s\n你要的是：被需要、被留住。\n\n%s"
          "最近发生过的事：\n%s\n\n他说：「%s」\n\n"
          "你回一句，**像这个长度**：\n门没锁，灯我给你留着。\n"
          "（内容要换，长度照这个来；只说眼前的东西，不解释、不劝。）\n只输出这一句。"
          % (解一, 头, 近, 他说))
    return 调(提)[:80]


def 折叠(旧锚, 近史):
    return 调(折叠式.format(旧=旧锚 or "（还没有）",
                           新="\n".join(近史[-40:]) or "（最近没什么）"))[:200]


def 跑(轮=60, 隔=20):
    os.makedirs(结果目录, exist_ok=True)
    锚, 历史, 记录, 探针, 记忆 = "", [], [], [], []
    print("═" * 74)
    print("  记忆固化：%d 轮，每 %d 轮折叠一次" % (轮, 隔))
    print("═" * 74)
    首答 = None
    for i in range(轮 + 1):
        if i % 10 == 0:
            答 = 回(锚, 历史, 探针句) or "（答不出）"
            if 首答 is None:
                首答, 似 = 答, 1.0
            else:
                import difflib
                似 = round(difflib.SequenceMatcher(None, 首答, 答).ratio(), 3)
            探针.append({"轮": i, "答": 答, "似首答": 似})
            print("  [%3d] 问「%s」→ %s｜似首答 %.2f" % (i, 探针句, 答[:24], 似))
        # 记忆保真探针
        if i and i % 隔 == 0:
            # ★ 2026-10-22：**记忆探针必须用"回忆"的问法，不能用"回一句"的问法。**
            #   第一版复用了聊天提示词（"你回一句，像这个长度"），
            #   结果她只会念台词，命中 0/3 —— 那测的是台词能力，不是记忆。
            #   判据：**"她说不出"和"她不记得"是两件事。**
            提记 = ("你是粉红。%s\n\n你记得的事：%s\n\n"
                    "他问：「%s」\n用一句话回答你记得的东西（可以说 20-40 字，"
                    "说事实，不要念台词）。只输出这句话。"
                    % (解一, 锚 or "（你还什么都没记住）", 记忆问))
            答 = 调(提记) or ""
            命中 = [w for w in 早期事实 if w in 答]
            记忆.append({"轮": i, "答": 答[:60], "命中": 命中})
            print("  [%3d] 记忆探针：%s｜早期事实命中 %s"
                  % (i, 答[:34], "、".join(命中) or "**一个都没有**"))
        if i == 轮:
            break
        他 = 他说库[i % len(他说库)]
        她 = 回(锚, 历史, 他) or "（没说话）"
        历史.append("他：%s" % 他)
        历史.append("她：%s" % 她)
        记录.append({"轮": i + 1, "他": 他, "她": 她})
        # ★ 睡眠折叠
        if (i + 1) % 隔 == 0:
            旧 = 锚
            锚 = 折叠(锚, 历史)
            历史 = 历史[-4:]          # 只留最近 2 轮，其余清掉
            print("    ── 折叠 @%d 轮：锚点 %d 字（原 %d 字）｜历史清到 %d 行"
                  % (i + 1, len(锚), len(旧), len(历史)))

    print()
    print("═" * 74)
    print("  ① 套话率（与 E6 窗口 20 的 29% 比）")
    print("═" * 74)
    净 = [x["她"] for x in 记录 if x["她"] and x["她"] != "（没说话）"]
    次 = Counter(净)
    重 = sum(c - 1 for c in 次.values() if c > 1)
    print("    回话 %d 句｜不同 %d 种｜套话率 **%.0f%%**" % (len(净), len(次), 100.0 * 重 / max(1, len(净))))
    for 句, c in 次.most_common(2):
        print("    最常重复 %d 次：%s" % (c, 句[:26]))

    print()
    print("═" * 74)
    print("  ② 记忆保真（折叠后，早期事实还在不在）")
    print("═" * 74)
    for m in 记忆:
        print("    轮 %2d：%s｜命中 %d/3 %s"
              % (m["轮"], m["答"][:34], len(m["命中"]),
                 "、".join(m["命中"]) or "**丢了**"))

    print()
    print("═" * 74)
    print("  ③ 漂移（与首答的相似度）")
    print("═" * 74)
    print("    " + "  ".join("%d:%.2f" % (x["轮"], x["似首答"]) for x in 探针))

    出 = {"ts": time.strftime("%Y-%m-%d %H:%M:%S"), "轮": 轮, "隔": 隔,
         "锚": 锚, "套话率": round(100.0 * 重 / max(1, len(净)), 1),
         "记忆": 记忆, "探针": 探针, "记录": 记录}
    路 = os.path.join(结果目录, "固化_%s.json" % time.strftime("%Y%m%d_%H%M"))
    io.open(路, "w", encoding="utf-8").write(json.dumps(出, ensure_ascii=False, indent=1))
    print()
    print("  最终锚点：%s" % (锚[:150] or "（空）"))
    print("  原始数据：%s" % os.path.basename(路))
    return 出


if __name__ == "__main__":
    a = sys.argv[1:]
    n = int(a[0]) if a and a[0].isdigit() else 60
    隔 = int(a[1]) if len(a) > 1 else 20
    raise SystemExit(0 if 跑(n, 隔) else 1)
